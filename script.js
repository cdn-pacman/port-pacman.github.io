const imageUrl = (path) => SOURCE + path.split("/").map(encodeURIComponent).join("/");
const container = document.getElementById("rom-container");
const latestContainer = document.getElementById("latest-container");
const dialog = document.getElementById("gallery-dialog");
let activeImages = [];
let activeImage = 0;

function makeCard(rom, index, featured = false) {
  const card = document.createElement("article");
  card.className = `rom-card${featured ? " featured-card" : ""}`;
  card.style.setProperty("--card-order", index);

  const cover = document.createElement("button");
  cover.type = "button";
  cover.className = "rom-cover";
  cover.setAttribute("aria-label", `View screenshots for ${rom.title}`);
  const image = document.createElement("img");
  image.src = imageUrl(rom.images[0]);
  image.alt = `${rom.title} ROM screenshot`;
  image.loading = featured ? "eager" : "lazy";
  image.onerror = () => { cover.classList.add("cover-unavailable"); image.remove(); };
  cover.append(image);
  const count = document.createElement("span");
  count.className = "image-count";
  count.textContent = `▧  ${rom.images.length} screenshot${rom.images.length === 1 ? "" : "s"}`;
  cover.append(count);
  cover.addEventListener("click", () => openGallery(rom));

  const content = document.createElement("div");
  content.className = "rom-content";
  const label = document.createElement("div");
  label.className = "rom-label";
  label.textContent = featured ? "LATEST PORT" : "CUSTOM ROM PORT";
  const title = document.createElement("h3");
  title.textContent = rom.title;
  const tags = document.createElement("div");
  tags.className = "rom-tags";
  rom.meta.forEach((value) => {
    const tag = document.createElement("span");
    tag.textContent = value;
    tags.append(tag);
  });
  const description = document.createElement("p");
  description.className = "rom-description";
  description.textContent = rom.desc;
  content.append(label, title, tags, description);

  const actions = document.createElement("div");
  actions.className = "rom-actions";
  const download = document.createElement("a");
  download.className = "download-button";
  download.href = rom.url;
  download.target = "_blank";
  download.rel = "noopener noreferrer";
  download.textContent = "View release ↗";
  const screenshots = document.createElement("button");
  screenshots.type = "button";
  screenshots.className = "gallery-button";
  screenshots.textContent = "Screenshots";
  screenshots.addEventListener("click", () => openGallery(rom));
  actions.append(download, screenshots);
  card.append(cover, content, actions);
  return card;
}

function openGallery(rom) {
  activeImages = rom.images;
  activeImage = 0;
  document.getElementById("gallery-title").textContent = rom.title;
  showImage();
  if (!dialog.open) dialog.showModal();
}

function showImage() {
  const image = document.getElementById("gallery-image");
  image.src = imageUrl(activeImages[activeImage]);
  image.alt = `${document.getElementById("gallery-title").textContent} screenshot ${activeImage + 1}`;
  image.onerror = () => { image.alt = "Screenshot could not be loaded from the original site."; };
  document.getElementById("gallery-count").textContent = `${activeImage + 1} / ${activeImages.length}`;
}

function moveImage(direction) {
  if (!activeImages.length) return;
  activeImage = (activeImage + direction + activeImages.length) % activeImages.length;
  showImage();
}

document.getElementById("year").textContent = new Date().getFullYear();
latestContainer.append(makeCard(roms[0], 0, true));
roms.forEach((rom, index) => container.append(makeCard(rom, index)));
document.getElementById("close-gallery").addEventListener("click", () => dialog.close());
document.getElementById("previous-image").addEventListener("click", () => moveImage(-1));
document.getElementById("next-image").addEventListener("click", () => moveImage(1));
dialog.addEventListener("click", (event) => { if (event.target === dialog) dialog.close(); });
document.addEventListener("keydown", (event) => {
  if (!dialog.open) return;
  if (event.key === "ArrowLeft") moveImage(-1);
  if (event.key === "ArrowRight") moveImage(1);
});
